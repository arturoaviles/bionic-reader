#!/usr/bin/env bash
set -euo pipefail
repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_root"
mode=${1:---write}
[[ $mode == --write || $mode == --check ]] || {
  printf 'Usage: build-go-engine.sh [--write|--check]\n' >&2
  exit 64
}
temporary=$(mktemp -d)
trap 'rm -rf "$temporary"' EXIT
build_root="${CARGO_TARGET_DIR:-$repo_root/target}/go-engine"
mkdir -p "$build_root"
build_root=$(cd "$build_root" && pwd)
# Canonical host, source/cache paths and flags keep Cargo's crate identities and
# linker ordering independent of the contributor's OS and checkout location.
docker run --rm --platform linux/amd64 \
  --mount "type=bind,src=$repo_root,dst=/source,readonly" \
  --mount "type=bind,src=$build_root,dst=/build" \
  --env CARGO_HOME=/build/cargo --env CARGO_TARGET_DIR=/build/target \
  --env 'RUSTFLAGS=--remap-path-prefix=/source=/src/bionic-reader --remap-path-prefix=/build/cargo=/cargo' \
  --workdir /source \
  rust:1.85.1-slim-bookworm@sha256:3490aa77d179a59d67e94239cca96dd84030b564470859200f535b942bdffedf \
  bash -eu -c 'rustup target add wasm32-wasip1 --toolchain 1.85.1; cargo +1.85.1 build --locked --release --target wasm32-wasip1 --package bionic-reader-go'
cp "$build_root/target/wasm32-wasip1/release/bionic-reader-go.wasm" "$temporary/engine.wasm"
python3 - "$temporary" <<'PY'
import hashlib
import sys
import tomllib
from pathlib import Path

output = Path(sys.argv[1])
version = tomllib.loads(Path("Cargo.toml").read_text())["workspace"]["package"]["version"]
digest = hashlib.sha256((output / "engine.wasm").read_bytes()).hexdigest()
(output / "engine_version.go").write_text(
    '// Code generated by scripts/build-go-engine.sh; DO NOT EDIT.\n'
    'package bionicreader\n\n'
    '// Version is the Cargo-owned package and embedded-engine version.\n'
    f'const Version = "{version}"\n\n'
    f'const engineSHA256 = "{digest}"\n'
)
PY
if [[ $mode == --check ]]; then
  cmp "$temporary/engine.wasm" internal/engine/engine.wasm
  cmp "$temporary/engine_version.go" engine_version.go
else
  mkdir -p internal/engine
  cp "$temporary/engine.wasm" internal/engine/engine.wasm
  cp "$temporary/engine_version.go" engine_version.go
fi
